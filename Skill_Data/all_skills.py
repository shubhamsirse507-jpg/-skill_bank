def get_all_skills_summary():
    """Returns a list of all supported skill categories and titles."""
    categories = {}
    for key, data in GLOBAL_SKILL_DATABASE.items():
        cat = data['category']
        if cat not in categories:
            categories[cat] = []
        categories[cat].append(data['title'])
    return categories


def search_global_skills(query):
    """Searches the database for matching skills across technical, creative, business, lifestyle, etc."""
    query_lower = query.lower()
    matches = []

    for key, data in GLOBAL_SKILL_DATABASE.items():
        if key in query_lower or data['title'].lower() in query_lower or data['category'].lower() in query_lower:
            matches.append(data)

    if not matches:
        # Check partial word matches
        for key, data in GLOBAL_SKILL_DATABASE.items():
            words = query_lower.split()
            if any(w in data['title'].lower() or w in data['description'].lower() for w in words if len(w) > 3):
                matches.append(data)

    return matches
